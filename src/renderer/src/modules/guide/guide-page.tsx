const SECTION_IDS = sections(null).map((s) => s.id)

/** Onboarding / help: everything in one page with a scroll-spy table of contents and an FAQ. */
export function GuidePage() {
  const navigate = useNavigate()
  const { hash } = useLocation()
  const scroller = useRef<HTMLDivElement>(null)
  const [active, setActive] = useState(SECTION_IDS[0])
  const [openFaq, setOpenFaq] = useState<Set<string>>(() => new Set())

  const setFaqOpen = (id: string, open: boolean): void =>
    setOpenFaq((prev) => {
      const next = new Set(prev)
      if (open) next.add(id)
      else next.delete(id)
      return next
    })

  const list = sections(<FaqList openIds={openFaq} setOpen={setFaqOpen} />)

  useEffect(() => {
    const root = scroller.current
    if (!root) return
    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries.filter((e) => e.isIntersecting).sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top)
        if (visible[0]) setActive(visible[0].target.id)
      },
      { root, rootMargin: '0px 0px -65% 0px', threshold: 0 }
    )
    for (const id of SECTION_IDS) {
      const el = root.querySelector(`#${id}`)
      if (el) observer.observe(el)
    }
    return () => observer.disconnect()
  }, [])

  // Deep links from other screens: /guide#faq-links opens that answer, /guide#data jumps to a section.
  useEffect(() => {
    const target = decodeURIComponent(hash.replace(/^#/, ''))
    if (!target) return
    if (target.startsWith('faq-')) {
      const id = target.slice(4)
      if (!FAQ.some((f) => f.id === id)) return
      setFaqOpen(id, true)
      // After the collapsible opens, bring the answer into view.
      requestAnimationFrame(() => scroller.current?.querySelector(`#${CSS.escape(target)}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' }))
      setActive('faq')
    } else if (SECTION_IDS.includes(target)) {
      scroller.current?.querySelector(`#${CSS.escape(target)}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' })
      setActive(target)
    }
  }, [hash])

  const jump = (id: string): void => {
    scroller.current?.querySelector(`#${id}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' })
    setActive(id)
  }

  return (
    <Page>
      <PageHeader
        title="Гайд по Vault"
        subtitle="Усе про розділи, гарячі клавіші, де лежать ваші дані, і відповіді на часті питання."
        actions={
          <Button variant="soft" onClick={() => navigate('/settings')}>
            <BookOpen /> Налаштування
          </Button>
        }
      />
      <div className="flex min-h-0 flex-1 gap-6 px-8 pb-8">
        <nav className="w-56 shrink-0 overflow-y-auto" aria-label="Зміст">
          <ItemGroup className="gap-0.5">
            {list.map((s) => (
              <Item key={s.id} asChild size="xs" variant={active === s.id ? 'active' : 'default'} className="rounded-full px-3">
                <button type="button" className="w-full text-left" onClick={() => jump(s.id)} aria-current={active === s.id || undefined}>
                  <s.icon className={cn('size-4 shrink-0', active === s.id ? 'text-ink-accent' : 'text-muted-foreground')} />
                  <ItemContent className="min-w-0">
                    <ItemTitle className="w-full truncate font-normal">{s.title}</ItemTitle>
                  </ItemContent>
                </button>
              </Item>
            ))}
          </ItemGroup>
        </nav>
        <div ref={scroller} className="min-w-0 flex-1 overflow-y-auto scroll-smooth pr-2">
          <div className="flex flex-col gap-3 pb-[40vh]">
            {list.map((s) => (
              <Card key={s.id} id={s.id} className="scroll-mt-2">
                <CardContent className="flex flex-col gap-4">
                  <div className="flex items-center justify-between gap-4">
                    <h2 className="font-display flex items-center gap-3 text-[24px] leading-tight">
                      <span className="grid size-10 place-items-center rounded-full bg-card">
                        <s.icon className="size-5" />
                      </span>
                      {s.title}
                    </h2>
                    {s.route && (
                      <Button variant="subtle" size="xs" onClick={() => navigate(s.route!)}>
                        Відкрити розділ <ArrowUpRight />
                      </Button>
                    )}
                  </div>
                  {s.body}
                </CardContent>
              </Card>
            ))}
          </div>
        </div>
      </div>
    </Page>
  )
}
